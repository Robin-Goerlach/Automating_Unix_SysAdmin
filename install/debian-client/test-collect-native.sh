#!/bin/sh
set -eu
[ "$(id -u)" -ne 0 ] || { echo 'Native collection test SKIPPED: root'; exit 0; }
here=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
tmp=$(mktemp -d); reports=
cleanup(){ for report in $reports; do rm -rf -- "$report"; done; rm -rf -- "$tmp"; }
trap cleanup EXIT
umask 077
mkdir -p "$tmp/source/etc"
etc=$tmp/source/etc
printf 'ID=debian\nVERSION_ID="13"\n' > "$etc/os-release"
printf 'old\n' > "$etc/hostname"
printf '127.0.0.1 localhost\n127.0.1.1 old.lab.invalid old\n' > "$etc/hosts"
printf 'nameserver 192.0.2.99\nsearch old.invalid\n' > "$etc/resolv.conf"
printf 'workstation\tsite_workstation\tmodern\troles/workstation.tsv\n' > "$tmp/roles"
printf 'node.lab.invalid\t192.0.2.40\tdebian\tworkstation\t\tbaseline\n' > "$tmp/hosts"
run(){ "$here/collect-native.sh" --root="$tmp/source" --hostname=node.lab.invalid --inventory="$tmp/hosts" --roles="$tmp/roles" --site="$here/site.example.conf" "$@"; }
collect(){ report=$(sed -n 's/^Acceptance report: //p' "$tmp/out"); if [ -n "$report" ]; then case "$report" in /tmp/sasd-native-acceptance.*) reports="$reports $report" ;; *) exit 1 ;; esac; fi; }
manifest(){ (cd "$etc" && sha256sum hostname hosts resolv.conf os-release && stat -c '%n %u:%g:%a' hostname hosts resolv.conf os-release); }
manifest > "$tmp/before"
rc=0; run > "$tmp/out" || rc=$?; [ "$rc" -eq 3 ]; collect
[ "$(cat "$report/status")" = COLLECTED_NOT_AUTHORIZED ]
[ "$(stat -c %a "$report")" = 700 ]
[ "$(cat "$report/scope")" = FIXTURE_READ_ONLY ]
(cd "$report" && sha256sum -c input.sha256)
[ "$(cat "$report/rehearsal/status")" = PREPARED_NOT_AUTHORIZED ]
grep -q '^G2[[:space:]]BLOCKED' "$report/gates.tsv"
grep -q '^G3[[:space:]]OPEN[[:space:]]experimental-writer-not-authorized$' "$report/gates.tsv"
grep -q '^G5[[:space:]]NOT_RUN' "$report/gates.tsv"
! grep -q '^dns-' "$report/commands.tsv"
grep -q '^rehearsal[[:space:]]0$' "$report/commands.tsv"
manifest > "$tmp/after"; cmp "$tmp/before" "$tmp/after"
# Managed resolver stays blocked; retain the unsuccessful rehearsal evidence.
printf '# Generated by NetworkManager\n' >> "$etc/resolv.conf"
manifest > "$tmp/before"
rc=0; run > "$tmp/out" || rc=$?; [ "$rc" -eq 3 ]; collect
grep -q '^G2[[:space:]]BLOCKED' "$report/gates.tsv"
grep -q '^resolver-owner-hint[[:space:]]MANAGED_HINT' "$report/preflight.tsv"
[ "$(cat "$report/rehearsal/status")" != PREPARED_NOT_AUTHORIZED ]
manifest > "$tmp/after"; cmp "$tmp/before" "$tmp/after"
reject(){ rc=0; run "$@" > "$tmp/out" 2>&1 || rc=$?; [ "$rc" -eq 2 ]; collect; }
reject --apply
reject --live
reject --probe-name=node.lab.invalid --probe-address=192.0.2.40
printf 'other.lab.invalid\t192.0.2.40\tdebian\tworkstation\t\tbaseline\n' > "$tmp/hosts"
reject
[ "$(cat "$report/status")" = STARTED_NOT_AUTHORIZED ]
! grep -q '^preflight' "$report/commands.tsv"
echo 'Native evidence collection tests passed'
