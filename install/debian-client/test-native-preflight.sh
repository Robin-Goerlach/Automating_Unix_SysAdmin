#!/bin/sh
# Static fixtures must never call runtime tools or execute os-release data.
set -eu
here=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
tmp=$(mktemp -d); trap 'rm -rf -- "$tmp"' EXIT
mkdir -p "$tmp/root/etc" "$tmp/root/usr/lib"
printf 'ID=debian\nVERSION_ID="12"\nEVIL=$(touch %s/pwned)\n' "$tmp" > "$tmp/root/usr/lib/os-release"
ln -s ../usr/lib/os-release "$tmp/root/etc/os-release"
printf 'node\n' > "$tmp/root/etc/hostname"
printf 'nameserver 192.0.2.53\n' > "$tmp/root/etc/resolv.conf"
run(){ perl "$here/native-preflight.pl" --root="$tmp/root" --hostname=node.lab.invalid --address=192.0.2.40 "$@"; }
check(){ awk -F '\t' -v k="$1" -v s="$2" -v v="$3" '$1==k && $2==s && $3==v {ok=1} END{exit !ok}' "$tmp/out"; }
hashes(){ (cd "$tmp/root" && sha256sum etc/hostname etc/resolv.conf usr/lib/os-release); }
hashes > "$tmp/before"; run > "$tmp/out"; hashes > "$tmp/after"; cmp "$tmp/before" "$tmp/after"
check os DETECTED debian:12
check stored-hostname MATCH node
check resolver-owner-hint UNKNOWN_REGULAR 'ownership unproven'
check runtime-hostname NOT_RUN fixture
check nss-probe NOT_RUN fixture
check native-apply NOT_AUTHORIZED 'diagnostics only'
[ ! -e "$tmp/pwned" ]
for pair in 'systemd-resolved:/run/systemd/resolve/stub-resolv.conf' 'resolvconf:../run/resolvconf/resolv.conf' 'NetworkManager:/run/NetworkManager/resolv.conf'; do
    rm "$tmp/root/etc/resolv.conf"; ln -s "${pair#*:}" "$tmp/root/etc/resolv.conf"
    run > "$tmp/out"; check resolver-owner-hint MANAGED_HINT "${pair%%:*}"
done
rm "$tmp/root/etc/resolv.conf"; ln -s /etc/passwd "$tmp/root/etc/resolv.conf"
run > "$tmp/out"; check resolver-owner-hint UNKNOWN 'unrecognized symlink'
rm "$tmp/root/etc/resolv.conf"; printf '# Generated by NetworkManager\n' > "$tmp/root/etc/resolv.conf"
printf 'wrong\n' > "$tmp/root/etc/hostname"
run > "$tmp/out"; check resolver-owner-hint MANAGED_HINT NetworkManager; check stored-hostname DRIFT wrong
printf 'ID=ubuntu\nVERSION_ID=24.04\n' > "$tmp/root/usr/lib/os-release"
run > "$tmp/out"; check os OUT_OF_SCOPE ubuntu:24.04
printf 'ID=debian\nID=ubuntu\nVERSION_ID=13\n' > "$tmp/root/usr/lib/os-release"
run > "$tmp/out"; check os UNKNOWN 'release data incomplete'
rm "$tmp/root/etc/os-release"; ln -s /etc/passwd "$tmp/root/etc/os-release"
run > "$tmp/out"; check os UNKNOWN 'release data incomplete'
reject(){ rc=0; "$@" > "$tmp/out" 2>&1 || rc=$?; [ "$rc" -eq 2 ]; }
reject run --live
reject run --probe-name=test.lab.invalid --probe-address=192.0.2.55
reject perl "$here/native-preflight.pl" --root=/ --hostname=node.lab.invalid --address=192.0.2.40
reject perl "$here/native-preflight.pl" --root="$tmp/root" --hostname='bad;host' --address=192.0.2.40
reject perl "$here/native-preflight.pl" --root="$tmp/root" --hostname=node.lab.invalid --address=192.0.2.040
printf 'Native preflight static tests passed\n'
