#!/bin/sh
set -eu
[ "$(id -u)" -ne 0 ] || { echo 'Native review test SKIPPED: root'; exit 0; }
here=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
tmp=$(mktemp -d); reports=
cleanup(){ for report in $reports; do rm -rf -- "$report"; done; rm -rf -- "$tmp"; }
trap cleanup EXIT
umask 077
mkdir -p "$tmp/source/etc"
etc=$tmp/source/etc
printf 'ID=debian\nVERSION_ID="13"\n' > "$etc/os-release"
printf 'old\n' > "$etc/hostname"
printf '127.0.0.1 localhost\n127.0.1.1 old.lab.invalid old\n::1 localhost\n192.0.2.22 other.lab.invalid other\n' > "$etc/hosts"
printf 'options timeout:2\nnameserver 192.0.2.99\nsearch old.invalid\n' > "$etc/resolv.conf"
chmod 644 "$etc/hostname" "$etc/hosts" "$etc/resolv.conf"
printf 'workstation\tsite_workstation\tmodern\troles/workstation.tsv\n' > "$tmp/roles"
printf 'node.lab.invalid\t192.0.2.40\tdebian\tworkstation\t\tbaseline\n' > "$tmp/hosts"
run(){ "$here/prepare-native.sh" --source-root="$tmp/source" --hostname=node.lab.invalid --site="$here/site.example.conf" --inventory="$tmp/hosts" --roles="$tmp/roles" "$@"; }
collect(){ report=$(sed -n 's/^Native review: //p' "$tmp/out"); if [ -n "$report" ]; then case "$report" in /tmp/sasd-native-review.*) reports="$reports $report" ;; *) exit 1 ;; esac; fi; }
manifest(){ (cd "$etc" && sha256sum hostname hosts resolv.conf && stat -c '%n %a %u %g' hostname hosts resolv.conf); }
manifest > "$tmp/before"
run > "$tmp/out"; collect
[ "$(cat "$report/status")" = PREPARED_NOT_AUTHORIZED ]
[ "$(cat "$report/scope")" = FIXTURE_SOURCE ]
[ "$(stat -c %a "$report")" = 700 ]
[ "$(grep -c PROPOSED "$report/changes.tsv")" -eq 3 ]
for name in hostname hosts resolv.conf; do cmp "$etc/$name" "$report/original/$name"; done
grep -qx 'node' "$report/desired/hostname"
grep -qx '192.0.2.22 other.lab.invalid other' "$report/desired/hosts"
grep -qx 'options timeout:2' "$report/desired/resolv.conf"
grep -q 'native-apply.*NOT_AUTHORIZED' "$report/preflight.tsv"
manifest > "$tmp/after"; cmp "$tmp/before" "$tmp/after"
# A source already matching the candidate should produce no proposed changes.
for name in hostname hosts resolv.conf; do cp "$report/desired/$name" "$etc/$name"; done
run > "$tmp/out"; collect
[ "$(grep -c UNCHANGED "$report/changes.tsv")" -eq 3 ]
reject(){ rc=0; "$@" > "$tmp/out" 2>&1 || rc=$?; [ "$rc" -ne 0 ]; collect; if [ -n "$report" ]; then [ "$(cat "$report/status")" != PREPARED_NOT_AUTHORIZED ]; fi; }
reject run --apply
reject run --live
printf 'ID=ubuntu\nVERSION_ID="24.04"\n' > "$etc/os-release"; reject run
printf 'ID=debian\nVERSION_ID="13"\n' > "$etc/os-release"
printf '# Generated by NetworkManager\n' >> "$etc/resolv.conf"; reject run
mv "$etc/resolv.conf" "$tmp/saved"; ln -s "$tmp/saved" "$etc/resolv.conf"; reject run
rm "$etc/resolv.conf"; mv "$tmp/saved" "$etc/resolv.conf"
sed -i '/Generated by NetworkManager/d' "$etc/resolv.conf"
chmod 666 "$etc/hosts"; reject run; chmod 644 "$etc/hosts"
ln "$etc/hosts" "$tmp/linked"; reject run; rm "$tmp/linked"
printf '192.0.2.44 node.lab.invalid node\n' >> "$etc/hosts"
manifest > "$tmp/conflict"; reject run; manifest > "$tmp/after"; cmp "$tmp/conflict" "$tmp/after"
printf 'other.lab.invalid\t192.0.2.40\tdebian\tworkstation\t\tbaseline\n' > "$tmp/hosts"; reject run
echo 'Native review rehearsal tests passed'
